import test from 'node:test';
import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const url = process.env.GAME_TEST_URL ?? 'http://localhost:3000';

test('mobile selection shares one 3D studio, rotates, and carries the chosen model into training and the HUD', {timeout:90000}, async t => {
  const browser = await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH,args:['--use-angle=metal','--enable-gpu','--ignore-gpu-blocklist']});
  t.after(()=>browser.close());
  const context = await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:3,isMobile:true,hasTouch:true,reducedMotion:'reduce'});
  const page = await context.newPage(), errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`${url}/local`);
  await page.locator('.hero-roster').scrollIntoViewIfNeeded();
  await page.waitForFunction(()=>[...document.querySelectorAll('.hero-roster canvas')].every(c=>Number(c.dataset.triangles)>0));
  const portraits=await page.locator('.hero-roster canvas').evaluateAll(cs=>cs.map(c=>({model:c.dataset.model,studio:c.dataset.studio,triangles:Number(c.dataset.triangles),pixels:c.getContext('2d').getImageData(0,0,c.width,c.height).data.some((n,i)=>i%4===3&&n>0)})));
  assert.equal(portraits.length,15);
  assert.equal(new Set(portraits.map(c=>c.model)).size,15);
  assert.equal(new Set(portraits.map(c=>c.studio)).size,1,'all thumbnails reuse the same WebGL context');
  assert.ok(portraits.every(c=>c.pixels&&c.triangles<=800),'models are visible and stay under 800 triangles, including the contact disc');
  await page.getByRole('button',{name:'Skateuse des Sans-suite',exact:true}).click();
  const hero=page.locator('.hero-preview canvas');
  await page.waitForFunction(()=>document.querySelector('.hero-preview canvas').dataset.model==='skater');
  const before=await hero.getAttribute('data-rotation');
  await page.getByRole('button',{name:'Tourner le personnage à droite'}).click();
  await page.waitForFunction(before=>document.querySelector('.hero-preview canvas').dataset.rotation!==before,before);
  await page.getByPlaceholder('Mika').fill('Zoé');
  await page.getByRole('button',{name:'Entrer dans la partie',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.initiation-flight canvas')?.dataset.model==='skater');
  assert.equal(await page.locator('.initiation-card img[src*="characters"]').count(),0);
  await page.getByRole('button',{name:'Passer l’initiation'}).click();
  await page.waitForFunction(()=>document.querySelector('.journey-card__portrait canvas')?.dataset.model==='skater');
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('louchomage:v2')));
  assert.equal(saved.players[0].characterId,'skater'); assert.equal(saved.events.length,0);
  await page.getByRole('button',{name:/Ouvrir le carnet/}).click();
  await page.waitForFunction(()=>document.querySelector('.journal-hero canvas')?.dataset.model==='skater');
  assert.ok(await page.locator('.adventure-menu').evaluate(n=>n.scrollWidth<=n.clientWidth));
  await page.keyboard.press('Escape');
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('.journey-card__portrait canvas')?.dataset.model==='skater');
  assert.equal(await page.locator('.character-screen').count(),0);
  assert.deepEqual(errors,[]);
});
